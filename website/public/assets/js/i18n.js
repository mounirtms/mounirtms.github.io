// i18n Functions
function setLanguage(lang) {
    if (!translations[lang]) return;
    
    // Update HTML lang and dir attributes
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });
    
    // Update active state on language buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    
    // Save preference
    localStorage.setItem('mab-lang', lang);
}

function initLanguage() {
    // Check for saved preference, browser language, or default to English
    const saved = localStorage.getItem('mab-lang');
    const browserLang = navigator.language.slice(0, 2);
    const defaultLang = (saved || (translations[browserLang] ? browserLang : 'en'));
    setLanguage(defaultLang);
}
